-- =============================================================================
-- Bazar de Fábrica Lizie — agendamento
-- Modelo de segurança:
--   * RLS ligado e SEM políticas: anon/authenticated não leem nem escrevem nada.
--   * Toda escrita passa pela função SECURITY DEFINER bazar_agendar().
--   * CPF nunca é armazenado em texto claro: guardamos HMAC-SHA256 com pepper
--     aleatório criado no Supabase Vault no momento da migração.
--   * Leitura pública apenas de horários/vagas (sem dado pessoal).
-- =============================================================================

create extension if not exists pgcrypto with schema extensions;

-- -----------------------------------------------------------------------------
-- Configuração do evento (linha única)
-- -----------------------------------------------------------------------------
create table public.bazar_config (
  id            smallint primary key default 1 check (id = 1),
  evento_nome   text        not null default 'Bazar de Fábrica Lizie',
  evento_data   date        not null,
  permanencia_horas smallint not null default 1 check (permanencia_horas between 1 and 6),
  aberto         boolean     not null default true,
  atualizado_em timestamptz not null default now()
);

insert into public.bazar_config (id, evento_nome, evento_data)
values (1, 'Bazar de Fábrica Lizie', date '2026-12-01');

-- -----------------------------------------------------------------------------
-- Horários (30 vagas por horário)
-- -----------------------------------------------------------------------------
create table public.bazar_horarios (
  id        smallint generated by default as identity primary key,
  hora      time     not null unique,
  vagas_max smallint not null default 30 check (vagas_max between 1 and 30),
  ativo     boolean  not null default true
);

insert into public.bazar_horarios (hora) values
  ('09:00'), ('10:00'), ('11:00'), ('12:00'),
  ('13:00'), ('14:00'), ('15:00'), ('16:00');

-- -----------------------------------------------------------------------------
-- Inscrições
-- -----------------------------------------------------------------------------
create table public.bazar_inscricoes (
  id              uuid        primary key default gen_random_uuid(),
  nome            text        not null check (char_length(nome) between 3 and 120),
  cpf_hash        text        not null unique,
  cpf_mascarado   text        not null,
  email           text        not null check (char_length(email) between 5 and 254),
  celular         text        not null check (celular ~ '^[0-9]{10,11}$'),
  horario_id      smallint    not null references public.bazar_horarios (id),
  como_soube      text        not null,
  aceita_novidades boolean    not null default false,
  aceita_termos   boolean     not null default false,
  criado_em       timestamptz not null default now(),
  constraint bazar_inscricoes_termos_obrigatorios check (aceita_termos)
);

create index bazar_inscricoes_horario_idx on public.bazar_inscricoes (horario_id);
create index bazar_inscricoes_email_idx   on public.bazar_inscricoes (lower(email));
create index bazar_inscricoes_celular_idx on public.bazar_inscricoes (celular);

-- -----------------------------------------------------------------------------
-- Controle de tentativas por IP (antiabuso / anti-flood)
-- Guarda apenas um hash SHA-256 do IP e expira em 2 dias.
-- -----------------------------------------------------------------------------
create table public.bazar_tentativas (
  id        bigint generated always as identity primary key,
  ip_hash   text        not null check (char_length(ip_hash) between 32 and 128),
  criado_em timestamptz not null default now()
);

create index bazar_tentativas_ip_idx on public.bazar_tentativas (ip_hash, criado_em desc);
create index bazar_tentativas_data_idx on public.bazar_tentativas (criado_em);

-- -----------------------------------------------------------------------------
-- Pepper do CPF (nunca versionado; gerado dentro do banco)
-- -----------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from vault.secrets where name = 'bazar_cpf_pepper') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'bazar_cpf_pepper',
      'Pepper HMAC para o CPF dos agendamentos do Bazar'
    );
  end if;
end;
$$;

-- -----------------------------------------------------------------------------
-- Validação de CPF (dígitos verificadores)
-- -----------------------------------------------------------------------------
create or replace function public.bazar_cpf_valido(p_cpf text)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_soma  integer;
  v_resto integer;
  i       integer;
begin
  if p_cpf is null or p_cpf !~ '^[0-9]{11}$' then
    return false;
  end if;

  -- rejeita sequências repetidas (000..., 111...)
  if p_cpf ~ '^([0-9])\1{10}$' then
    return false;
  end if;

  v_soma := 0;
  for i in 1..9 loop
    v_soma := v_soma + substr(p_cpf, i, 1)::integer * (11 - i);
  end loop;
  v_resto := (v_soma * 10) % 11;
  if v_resto = 10 then
    v_resto := 0;
  end if;
  if v_resto <> substr(p_cpf, 10, 1)::integer then
    return false;
  end if;

  v_soma := 0;
  for i in 1..10 loop
    v_soma := v_soma + substr(p_cpf, i, 1)::integer * (12 - i);
  end loop;
  v_resto := (v_soma * 10) % 11;
  if v_resto = 10 then
    v_resto := 0;
  end if;

  return v_resto = substr(p_cpf, 11, 1)::integer;
end;
$$;

-- -----------------------------------------------------------------------------
-- Leitura pública: horários e vagas restantes (sem dado pessoal)
-- -----------------------------------------------------------------------------
create or replace function public.bazar_horarios_disponiveis()
returns jsonb
language sql
security definer
stable
set search_path = ''
as $$
  select jsonb_build_object(
    'evento', (
      select jsonb_build_object(
        'nome', c.evento_nome,
        'data', c.evento_data,
        'permanencia_horas', c.permanencia_horas,
        'aberto', c.aberto
      )
      from public.bazar_config c
      where c.id = 1
    ),
    'horarios', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', h.id,
          'hora', to_char(h.hora, 'HH24:MI'),
          'vagas_max', h.vagas_max,
          'vagas_restantes', greatest(
            h.vagas_max - (
              select count(*) from public.bazar_inscricoes i where i.horario_id = h.id
            ), 0
          )
        )
        order by h.hora
      )
      from public.bazar_horarios h
      where h.ativo
    ), '[]'::jsonb)
  );
$$;

-- -----------------------------------------------------------------------------
-- Escrita: única porta de entrada, com validação e trava por horário
-- -----------------------------------------------------------------------------
create or replace function public.bazar_agendar(
  p_nome             text,
  p_email            text,
  p_cpf              text,
  p_celular          text,
  p_horario_id       smallint,
  p_como_soube       text,
  p_aceita_novidades boolean,
  p_aceita_termos    boolean,
  p_ip_hash          text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_nome      text := btrim(regexp_replace(coalesce(p_nome, ''), '\s+', ' ', 'g'));
  v_email     text := lower(btrim(coalesce(p_email, '')));
  v_cpf       text := regexp_replace(coalesce(p_cpf, ''), '\D', '', 'g');
  v_celular   text := regexp_replace(coalesce(p_celular, ''), '\D', '', 'g');
  v_pepper    text;
  v_hash      text;
  v_horario   public.bazar_horarios;
  v_ocupadas  integer;
  v_recentes  integer;
  v_id        uuid;
  v_restantes integer;
begin
  -- 1. Antiabuso por IP -------------------------------------------------------
  if p_ip_hash is null or p_ip_hash !~ '^[a-f0-9]{32,128}$' then
    raise exception 'REQUISICAO_INVALIDA';
  end if;

  select count(*) into v_recentes
  from public.bazar_tentativas
  where ip_hash = p_ip_hash
    and criado_em > now() - interval '10 minutes';

  if v_recentes >= 8 then
    raise exception 'MUITAS_TENTATIVAS';
  end if;

  insert into public.bazar_tentativas (ip_hash) values (p_ip_hash);

  delete from public.bazar_tentativas
  where criado_em < now() - interval '2 days';

  -- 2. Evento aberto ---------------------------------------------------------
  if not exists (select 1 from public.bazar_config where id = 1 and aberto) then
    raise exception 'INSCRICOES_ENCERRADAS';
  end if;

  -- 3. Validações ------------------------------------------------------------
  if char_length(v_nome) < 3 then
    raise exception 'NOME_INVALIDO';
  end if;

  if v_email !~ '^[^@\s]+@[^@\s]+\.[a-z]{2,}$' then
    raise exception 'EMAIL_INVALIDO';
  end if;

  if not public.bazar_cpf_valido(v_cpf) then
    raise exception 'CPF_INVALIDO';
  end if;

  if v_celular !~ '^[0-9]{10,11}$' then
    raise exception 'CELULAR_INVALIDO';
  end if;

  if coalesce(p_como_soube, '') not in (
    'Indicação de Amigos',
    'Instagram',
    'Facebook',
    'WhatsApp',
    'Passando na rua',
    'Outro'
  ) then
    raise exception 'ORIGEM_INVALIDA';
  end if;

  if p_aceita_termos is not true then
    raise exception 'TERMOS_OBRIGATORIOS';
  end if;

  select * into v_horario
  from public.bazar_horarios
  where id = p_horario_id and ativo;

  if not found then
    raise exception 'HORARIO_INVALIDO';
  end if;

  -- 4. CPF único (comparação por HMAC, sem guardar o número) -----------------
  select decrypted_secret into v_pepper
  from vault.decrypted_secrets
  where name = 'bazar_cpf_pepper'
  limit 1;

  if v_pepper is null then
    raise exception 'CONFIGURACAO_AUSENTE';
  end if;

  v_hash := encode(
    extensions.hmac(
      convert_to(v_cpf, 'UTF8'),
      convert_to(v_pepper, 'UTF8'),
      'sha256'
    ),
    'hex'
  );

  if exists (select 1 from public.bazar_inscricoes where cpf_hash = v_hash) then
    raise exception 'CPF_JA_CADASTRADO';
  end if;

  -- 5. Trava o horário: impede estourar as 30 vagas em acessos simultâneos --
  perform 1
  from public.bazar_horarios
  where id = v_horario.id
  for update;

  select count(*) into v_ocupadas
  from public.bazar_inscricoes
  where horario_id = v_horario.id;

  if v_ocupadas >= v_horario.vagas_max then
    raise exception 'HORARIO_ESGOTADO';
  end if;

  insert into public.bazar_inscricoes (
    nome, cpf_hash, cpf_mascarado, email, celular,
    horario_id, como_soube, aceita_novidades, aceita_termos
  ) values (
    v_nome,
    v_hash,
    '***.***.***-' || right(v_cpf, 2),
    v_email,
    v_celular,
    v_horario.id,
    p_como_soube,
    coalesce(p_aceita_novidades, false),
    true
  )
  returning id into v_id;

  v_restantes := greatest(v_horario.vagas_max - v_ocupadas - 1, 0);

  return jsonb_build_object(
    'ok', true,
    'protocolo', v_id,
    'horario', to_char(v_horario.hora, 'HH24:MI'),
    'vagas_restantes', v_restantes
  );
exception
  when unique_violation then
    raise exception 'CPF_JA_CADASTRADO';
end;
$$;

-- -----------------------------------------------------------------------------
-- Blindagem de permissões
-- -----------------------------------------------------------------------------
alter table public.bazar_config      enable row level security;
alter table public.bazar_horarios    enable row level security;
alter table public.bazar_inscricoes  enable row level security;
alter table public.bazar_tentativas  enable row level security;

-- Nenhuma política = nenhum acesso direto. Só o service_role (bypass RLS) e as
-- funções SECURITY DEFINER acima alcançam os dados.
revoke all on public.bazar_config     from anon, authenticated;
revoke all on public.bazar_horarios   from anon, authenticated;
revoke all on public.bazar_inscricoes from anon, authenticated;
revoke all on public.bazar_tentativas from anon, authenticated;

revoke all on sequence public.bazar_horarios_id_seq from anon, authenticated;
revoke all on sequence public.bazar_tentativas_id_seq from anon, authenticated;

revoke all on function public.bazar_cpf_valido(text) from public, anon, authenticated;
revoke all on function public.bazar_horarios_disponiveis() from public, anon, authenticated;
revoke all on function public.bazar_agendar(text, text, text, text, smallint, text, boolean, boolean, text) from public, anon, authenticated;

grant execute on function public.bazar_horarios_disponiveis() to service_role;
grant execute on function public.bazar_agendar(text, text, text, text, smallint, text, boolean, boolean, text) to service_role;

comment on table public.bazar_inscricoes is
  'Inscrições do bazar. CPF armazenado apenas como HMAC-SHA256 (pepper no Vault) + máscara.';
comment on function public.bazar_agendar is
  'Única via de escrita das inscrições. Valida dados, CPF, vagas e limite por IP.';
